/**
 * Downloads and processes the licensed placeholder photography listed in
 * scripts/placeholders.manifest.json.
 *
 *  - Resizes to a 2560px long edge (hero) / 2200px (others), progressive mozjpeg q82, metadata stripped
 *  - Generates a 16px WebP blur preview
 *  - Writes public/placeholders/ph-<id>.jpg and src/content/media.generated.ts
 *  - Generates public/textures/grain.png
 *
 * Usage: npm run placeholders            (skips files that already exist)
 *        npm run placeholders -- --force (re-downloads everything)
 *
 * Remove this script and the ph- files once the client's real photography is in the admin.
 */
import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const manifest = JSON.parse(await fs.readFile(path.join(root, "scripts/placeholders.manifest.json"), "utf8"));
const outDir = path.join(root, "public/placeholders");
const cacheDir = path.join(root, ".cache/placeholders");
const force = process.argv.includes("--force");
// Wikimedia rate-limits aggressively. It is disabled unless explicitly requested; already-cached
// Commons files are still processed from .cache/placeholders.
const allowCommons = process.argv.includes("--allow-commons");
const UA = "M3FotoPlaceholderFetcher/1.0 (one-off placeholder sourcing script)";

await fs.mkdir(outDir, { recursive: true });
await fs.mkdir(cacheDir, { recursive: true });

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const exists = (p) => fs.access(p).then(() => true, () => false);

async function download(url, dest) {
  for (let attempt = 1; attempt <= 8; attempt++) {
    const res = await fetch(url, { headers: { "User-Agent": UA }, redirect: "follow" });
    if (res.status === 429 || res.status >= 500) {
      const retryAfter = Number(res.headers.get("retry-after")) * 1000;
      const wait = Math.max(retryAfter || 0, 20000 * attempt);
      console.log(`  ${res.status}, retrying in ${wait / 1000}s`);
      await sleep(wait);
      continue;
    }
    if (!res.ok) throw new Error(`${res.status} ${url}`);
    await fs.writeFile(dest, Buffer.from(await res.arrayBuffer()));
    return;
  }
  throw new Error(`Gave up on ${url}`);
}

const records = [];
for (const item of manifest) {
  const raw = path.join(cacheDir, `${item.id}.src`);
  const file = `ph-${item.id}.jpg`;
  const out = path.join(outDir, file);
  if (item.source === "wikimedia-commons" && !allowCommons && !(await exists(raw))) {
    throw new Error(`${item.id}: Wikimedia downloads are disabled. Swap this entry to a local or Unsplash source, or pass --allow-commons.`);
  }
  if (force || !(await exists(raw))) {
    console.log(`↓ ${item.id}`);
    await download(item.download, raw);
    if (item.source === "wikimedia-commons") await sleep(15000);
  }
  const longEdge = item.id.startsWith("hero") ? 2560 : 2200;
  if (force || !(await exists(out))) {
    await sharp(raw)
      .rotate()
      .resize({ width: longEdge, height: longEdge, fit: "inside", withoutEnlargement: true })
      .jpeg({ quality: 82, progressive: true, mozjpeg: true })
      .toFile(out);
  }
  const meta = await sharp(out).metadata();
  const blur = await sharp(out).resize(16).webp({ quality: 40 }).toBuffer();
  records.push({
    id: item.id,
    src: `/placeholders/${file}`,
    width: meta.width,
    height: meta.height,
    blurDataURL: `data:image/webp;base64,${blur.toString("base64")}`,
    alt: item.alt,
    focal: item.focal,
    placeholder: true,
    credit: {
      author: item.author,
      license: item.license,
      licenseUrl: item.licenseUrl,
      sourceUrl: item.sourceUrl,
      ...(item.title ? { title: item.title } : {}),
    },
  });
  console.log(`✓ ${item.id} ${meta.width}×${meta.height}`);
}

const ts = `// AUTO-GENERATED by scripts/process-placeholders.mjs — do not edit by hand.
// Every entry is licensed placeholder photography, credited on /credits.
// Replace with the client's photography (via the admin in Milestone 5).
import type { MediaAsset } from "@/lib/schemas/content";

export const placeholderMedia: MediaAsset[] = ${JSON.stringify(records, null, 2)};
`;
await fs.writeFile(path.join(root, "src/content/media.generated.ts"), ts);

// Film grain texture: 192×192 greyscale noise as lossy WebP (~10 KB instead of ~100 KB PNG).
const grainPath = path.join(root, "public/textures/grain.webp");
if (force || !(await exists(grainPath))) {
  const size = 192;
  const buf = Buffer.alloc(size * size);
  for (let i = 0; i < size * size; i++) buf[i] = Math.floor(Math.random() * 256);
  await fs.mkdir(path.dirname(grainPath), { recursive: true });
  await sharp(buf, { raw: { width: size, height: size, channels: 1 } }).webp({ quality: 45 }).toFile(grainPath);
}

console.log(`\nProcessed ${records.length} placeholders.`);
